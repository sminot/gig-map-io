class Pangenome(Dataset):
    """
    Representation of a pangenome generated by gig-map.

    This is a minimal base class; concrete subclasses or helpers can add
    convenience methods for common gig-map outputs (e.g., gene presence/absence,
    annotations, etc.).

    DataFrame attributes are cached after first access to avoid reloading
    CSV files on subsequent accesses.
    """

    def __repr__(self) -> str:
        return f"Pangenome(directory={self.directory})"

    def __str__(self) -> str:
        return f"Pangenome(directory={self.directory})"

    def __format__(self, format_spec: str) -> str:
        return f"Pangenome(directory={self.directory})"

    @cached_property
    def unbinned_genes_all_genomes_html(self) -> str:
        """
        Gene by genome heatmap HTML loaded from bin_pangenome/heatmap.unbinned_genes_all_genomes.html.
        """
        path = self.directory / "bin_pangenome/heatmap.unbinned_genes_all_genomes.html"
        return path.read_text()

    @cached_property
    def gene_bins(self) -> pd.DataFrame:
        """
        Gene bins DataFrame loaded from bin_pangenome/gene_bins.csv.

        Returns
        -------
        DataFrame containing gene bin assignments.
        """
        path = self.directory / "bin_pangenome" / "gene_bins.csv"
        return (
            pd.read_csv(path)
            .assign(
                gene_label=lambda d: d.apply(
                    lambda r: f"{r['gene_id']} - {r['combined_name']}",
                    axis=1
                )
            )
        )

    @cached_property
    def ani_distances(self) -> pd.DataFrame:
        """
        ANI distances DataFrame loaded from distances.csv.gz.

        Returns
        -------
        DataFrame containing ANI distances.
        """
        path = self.directory / "distances.csv.gz"
        return pd.read_csv(path, index_col=0)

    @cached_property
    def align_genomes(self) -> pd.DataFrame:
        """
        Alignment of genomes from align/genomes.aln.csv.gz.
        """
        path = self.directory / "align" / "genomes.aln.csv.gz"
        df = pd.read_csv(path)

        # Add the bin label to the alignment
        df = df.assign(
            bin=df["sseqid"].apply(
                self.gene_bins.set_index("gene_id")["bin"].get
            )
        )
        return df

    @cached_property
    def n_bins(self) -> int:
        """
        Number of unique (non-null) bins in gene_bins.
        """
        return int(self.gene_bins["bin"].dropna().nunique())

    @cached_property
    def n_genes(self) -> int:
        """
        Number of genes which are part of bins in the pangenome.
        """
        return int(self.gene_bins.dropna(subset=["bin"]).shape[0])

    @cached_property
    def genome_content(self) -> pd.DataFrame:
        """
        Genome content DataFrame loaded from bin_pangenome/genome_content.long.csv.

        Returns
        -------
        DataFrame containing genome content data.
        """
        path = self.directory / "bin_pangenome" / "genome_content.long.csv"
        return pd.read_csv(path, low_memory=False)

    @cached_property
    def bin_presence_wide(self) -> pd.DataFrame:
        """
        Wide dataframe of bin presence/absence for each genome. Each column is a bin, each row is a genome.
        """
        return (
            self.genome_content
            .assign(present=(self.genome_content["prop_genes_detected"] >= 0.5).astype(int))
            .reindex(columns=["genome", "bin", "present"])
            .dropna()
            .drop_duplicates()
            .pivot(
                index="genome",
                columns="bin",
                values="present"
            )
            .fillna(0)
        )

    @cached_property
    def bin_size(self) -> pd.DataFrame:
        """
        Number of genes in each bin.
        """
        return self.gene_bins["bin"].value_counts()

    def bin_genome_heatmap(
        self,
        width: int = 500,
        height: int = 400,
        file_prefix: str | None = None
    ) -> go.Figure:
        """
        Heatmap of bin presence/absence for each genome.
        """

        # Perform hierarchical clustering on the rows and columns
        wide_sorted = sort_dataframe(
            sort_dataframe(
                self.bin_presence_wide.copy().T,
                method="ward"
            ).T,
            method="ward"
        )

        # Set the edges of the bins so that the widths match the number of genes
        x = [0] + self.bin_size.reindex(wide_sorted.columns.values).cumsum().tolist()

        fig = go.Figure(
            data=[
                go.Heatmap(
                    z=wide_sorted.values,
                    x=x,
                    colorscale="blues",
                    showscale=False
                )
            ],
            layout=go.Layout(
                xaxis_title="Gene",
                yaxis_title="Genome",
                template="simple_white",
                width=width,
                height=height
            )
        )
        # If save_image was provided, use the string as the file
        # prefix to write out HTML, PDF, PNG, and JSON
        save_image(fig, file_prefix)

        return fig

    def bin_size_histogram(
        self,
        bins: int = 30,
        width: int = 500,
        height: int = 400,
        file_prefix: str | None = None
    ) -> go.Figure:
        """
        Histogram of bin sizes.
        """
        # Get the bin sizes
        vals = self.bin_size.copy().apply(np.log10)

        counts, bins = np.histogram(
            vals,
            bins=bins,
            weights=self.bin_size.copy()
        )

        bin_names = [
            (
                f"{10**bins[i-1]:.0f} - {10**bins[i]:.0f}"
            )
            for i in range(1, len(bins))
        ]
        bins = 0.5 * (bins[:-1] + bins[1:])

        fig = px.bar(
            x=bins,
            y=counts,
            labels={'x':"Pangenome Bin Size (# of Genes)", 'y':'Total Gene Content'},
            template="plotly_white",
            hover_name=bin_names,
            width=width,
            height=height
        )
        # If save_image was provided, use the string as the file
        # prefix to write out HTML, PDF, PNG, and JSON
        save_image(fig, file_prefix)

        return fig

    @lru_cache
    def rarefaction_curve_data(_self, max_genomes: int = 100) -> pd.DataFrame:
        df = _self.bin_presence_wide * _self.bin_size
        return pd.DataFrame([
            dict(
                n_genomes=n_genomes,
                **pd.Series([
                    df.sample(n_genomes).max().sum()
                    for rep in range(100)
                ]).describe()
            )
            for n_genomes in range(1, min(max_genomes, df.shape[0]))
        ])

    def rarefaction_curve(
        self,
        max_genomes: int = 100,
        width: int = 500,
        height: int = 400,
        file_prefix: str | None = None
    ) -> go.Figure:
        """
        Rarefaction curve of the pangenome.

        Parameters
        ----------
        max_genomes: int
            Maximum number of genomes to simulate.

        Returns
        -------
        Plotly figure of the rarefaction curve.
        """
        # Simulate the number of genes recovered with different numbers of subsampled genomes
        rf = self.rarefaction_curve_data(max_genomes)

        fig = go.Figure(
            data=[
                go.Scatter(
                    x=rf["n_genomes"],
                    y=rf["50%"],
                    mode="lines",
                    line=dict(color='rgb(31, 119, 180)'),
                    showlegend=False
                ),
                go.Scatter(
                    x=rf['n_genomes'],
                    y=rf['75%'],
                    mode='lines',
                    marker=dict(color="#444"),
                    line=dict(width=0),
                    showlegend=False
                ),
                go.Scatter(
                    x=rf['n_genomes'],
                    y=rf['25%'],
                    marker=dict(color="#444"),
                    line=dict(width=0),
                    mode='lines',
                    fillcolor='rgba(68, 68, 68, 0.3)',
                    fill='tonexty',
                    showlegend=False
                )
            ],
            layout=go.Layout(
                xaxis_title="Number of Genomes",
                yaxis_title="Number of Genes",
                yaxis_range=[0, rf["75%"].max()],
                template="plotly_white",
                width=width,
                height=height
            )
        )
        # If save_image was provided, use the string as the file
        # prefix to write out HTML, PDF, PNG, and JSON
        save_image(fig, file_prefix)

        return fig

    def bin_gene_map(
        self,
        bin: str,
        width: int = 5,
        height: int = 5,
        remove_gene_id = True,
        remove_org_tag = True,
        text_offset = 0.05,
        file_prefix: str | None = None
    ) -> go.Figure:
        """
        Map of genes in a bin.
        """

        # Get the coordinates for every gene across every genome
        # Filter to just the genes in this bin
        aln = self.align_genomes.query(f"bin == '{bin}'")

        # Figure out the coordinates by looking at all of the contig alignments
        coords = Coords(aln)

        coords = coords.to_df()

        # Customize the names
        coords = coords.assign(
            gene_label=coords['gene'].apply(self.gene_bins.set_index("gene_id")["gene_label"].get),
            label=lambda d: d['gene_label'].apply(
                lambda gene: self.customize_label(gene, remove_gene_id, remove_org_tag)
            )
        )

        max_y = np.max([coords['start'].max(), coords['stop'].max()])
        min_y = np.min([coords['start'].min(), coords['stop'].min()])
        span_y = max_y - min_y

        coords = coords.assign(
            start_y=lambda d: (d['start'] - min_y) / span_y,
            stop_y=lambda d: (d['stop'] - min_y) / span_y
        )

        fig, ax = plt.subplots(figsize=(width, height))
        for ix, r in coords.iterrows():

            ax.annotate(
                "",
                xytext=(0, r['start_y']),
                xy=(0, r['stop_y']),
                arrowprops=dict(arrowstyle="->")
            )
            ax.plot([0, 0], [r['start_y'], r['stop_y']], linewidth=0)

            ax.annotate(
                '',
                xytext=(text_offset, (ix + 0.75) / coords.shape[0]),
                xy=(text_offset / 10., np.mean([r['start_y'], r['stop_y']])),
                arrowprops=dict(arrowstyle="-"),
                horizontalalignment='left',  # Align text to the right of its position
                verticalalignment='center'
            )
            ax.text(text_offset, (ix + 0.5) / coords.shape[0], r['label'])
        
        ax.axis("off")

        # If save_image was provided, use the string as the file
        # prefix to write out HTML, PDF, PNG, and JSON
        save_image(fig, file_prefix)

        # Optionally save the relative gene coordinates as CSV
        if file_prefix is not None:
            coords.to_csv(file_prefix + ".csv", index=False)

        return fig

    @staticmethod
    def customize_label(label: str, remove_gene_id: bool, remove_org_tag: bool):
        if remove_gene_id:
            if label.startswith("Bin "):
                label = " - ".join(label.split(" - ", 2)[[0, 2]])
            else:
                label = label.split(" - ", 1)[1]
        if remove_org_tag:
            if " [" in label:
                label = label.rsplit(" [", 1)[0]
            if "MULTISPECIES: " in label:
                label = label.replace("MULTISPECIES: ", "")

        return label

    def bin_presence_heatmap(
        self,
        bins: str | List[str],
        width: int = 500,
        height: int = 400,
        title: str = "Bin Presence Heatmap",
        show_ani_tree: bool = True,
        show_genome_names: bool = False,
        tree_proportion: float = 0.5,
        horizontal_spacing: float = 0.,
        file_prefix: str | None = None
    ) -> go.Figure:
        """
        Heatmap of bin presence/absence for each genome.
        Parameters
        ----------
        bins: str | List[str]
            The bins to plot.
        width: int
            The width of the figure.
        height: int
            The height of the figure.
        file_prefix: str | None
            The prefix for the file to save the figure to.

        Returns
        -------
        Plotly figure of the heatmap.
        """

        if isinstance(bins, str):
            bins = [bins]

        # Get the genomes that this bin is found in
        df = (
            self.genome_content
            .loc[self.genome_content["bin"].isin(bins)]
            .assign(present=1)
            .pivot_table(index="genome", columns="bin",values="present")
            .reindex(index=self.genome_content["genome"].unique(), columns=bins)
            .fillna(0)
            .astype(int)
        )
        df = df[df.index.notnull()]

        left_tree = self.ani_tree
        df = df.reindex(index=left_tree.leaves_list)

        fig = make_subplots(
            rows=1,
            cols=1 + int(show_ani_tree),
            shared_yaxes=True,
            horizontal_spacing=horizontal_spacing,
            column_widths=[tree_proportion, 1.-tree_proportion] if show_ani_tree else [1.]
        )
        if show_ani_tree:
            left_tree.plot_lines(fig, row=1, col=1)
            left_tree.plot_points(fig, mode="markers", row=1, col=1)

        fig.add_heatmap(
            z=df.values,
            x=df.columns.values,
            y=list(range(df.shape[0])),
            colorscale="blues",
            showscale=False,
            row=1,
            col=1 + int(show_ani_tree)
        )

        fig.update_layout(
            height=height,
            width=width,
            template="simple_white",
            title=dict(text=title, x=0.5, xanchor="center")
        )
        if show_genome_names:
            fig.update_yaxes(
                tickmode="array",
                tickvals=list(range(df.shape[0])),
                ticktext=df.index.values,
                side='right',
                anchor="x2"
            )
        else:
            fig.update_yaxes(
                visible=False
            )
        
        # If save_image was provided, use the string as the file
        # prefix to write out HTML, PDF, PNG, and JSON
        save_image(fig, file_prefix)
        return fig

    @cached_property
    def ani_tree(self) -> Phylogeny:
        # Get the ANI distances
        ani_dist = self.ani_distances.copy()

        # Make a distance matrix in BioPython format
        dm = DistanceMatrix(
            names=list(ani_dist.index.values),
            matrix=[
                l[:(i+1)]
                for i, l in enumerate(ani_dist.values.tolist())
            ]
        )

        # Compute a hash of the ani_dist DataFrame which can be used to identify the tree
        tree_hash = hashlib.sha256(ani_dist.to_csv().encode()).hexdigest()

        # Cache the NJ tree as Newick, using the hash as the filename
        cache_file = Path(f".cache/pangenome_ani_tree/{tree_hash}.nwk")
        if cache_file.exists():
            logger.info(f"Loading ANI tree from cache: {cache_file}")
            tree = Phylo.read(cache_file, "newick")
        else:
            logger.info(f"Computing ANI tree and caching to: {cache_file}")
            constructor = DistanceTreeConstructor()
            tree = constructor.nj(dm)
            tree.root_at_midpoint()
            cache_file.parent.mkdir(exist_ok=True, parents=True)
            Phylo.write(tree, cache_file, "newick")

        distances = pd.DataFrame(dm.matrix, index=dm.names, columns=dm.names)

        return Phylogeny(
            name="ANI",
            tree=tree,
            distances=distances
        )